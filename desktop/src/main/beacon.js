/**
 * Start serving. `info()` is called per request, so a rotated token or a new
 * address is picked up without a restart. Resolves with the bound server, or
 * rejects when the port is taken.
 */
function startBeacon({ port, info }) {
  const server = http.createServer((request, response) => {
    const url = new URL(request.url, "http://local");
    const hostHeader = request.headers.host || "";
    const { token, coordinatorPort, meshName, meshId, version, lanAddress } = info();
    const hostname = hostHeader.split(":")[0] && !/^(localhost|127\.)/.test(hostHeader) ? hostHeader.split(":")[0] : lanAddress;
    const web = `http://${hostname}:${port}`;
    const coordinator = `http://${hostname}:${coordinatorPort}`;

    const send = (status, type, body) => {
      response.writeHead(status, {
        "Content-Type": type,
        "Cache-Control": "no-store",
        "X-Content-Type-Options": "nosniff",
      });
      response.end(body);
    };

    if (request.method !== "GET" && request.method !== "HEAD") return send(405, "text/plain", "GET only\n");
    if (!token) return send(503, "text/plain", "# The mesh is still starting. Try again in a moment.\n");

    const route = url.pathname.replace(/\/+$/, "") || "/";
    if (route === "/join.ps1") return send(200, "text/plain; charset=utf-8", powershellScript({ web, coordinator, token }));
    if (route === "/join.sh") return send(200, "text/plain; charset=utf-8", shellScript({ web, coordinator, token }));
    if (route === "/gradapp.json") {
      return send(
        200,
        "application/json",
        JSON.stringify({ app: "gradapp", meshName, meshId, version, coordinator, web, token, coordinatorPort })
      );
    }
    if (route === "/api/health") return send(200, "application/json", JSON.stringify({ status: "ok", app: "gradapp" }));
    if (route.startsWith("/api/agent/")) {
      const file = decodeURIComponent(route.slice("/api/agent/".length));
      if (!AGENT_SET.has(file)) return send(404, "text/plain", "Not an agent file\n");
      try {
        const body = fs.readFileSync(path.join(engineDir(), file));
        return send(200, file.endsWith(".py") ? "text/x-python; charset=utf-8" : "text/plain; charset=utf-8", body);
      } catch {
        return send(404, "text/plain", "Missing\n");
      }
    }
    if (route === "/logo.png" || route === "/favicon.ico") {
      try {
        response.writeHead(200, { "Content-Type": "image/png", "Cache-Control": "public, max-age=86400" });
        return response.end(fs.readFileSync(path.join(assetsDir(), "logo.png")));
      } catch {
        return send(404, "text/plain", "Missing\n");
      }
    }
    if (route === "/" || route === "/join") return send(200, "text/html; charset=utf-8", joinPage({ web, meshName }));
    return send(404, "text/plain", "Not found\n");
  });

  return new Promise((resolve, reject) => {
    server.once("error", reject);
    server.listen(port, "0.0.0.0", () => {
      server.off("error", reject);
      resolve(server);
    });
  });
}

module.exports = { startBeacon };
