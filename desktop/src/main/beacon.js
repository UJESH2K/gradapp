"use strict";

/**
 * The join surface a hosting GradApp offers its network, on port 3000.
 *
 * GradMesh's Next.js dashboard serves this today: /join.ps1, /join.sh and the
 * agent files they download. GradApp serves the same paths, byte-compatible, so
 * every way of joining keeps working against a GradApp host:
 *
 *   - another GradApp finds the host and reads /gradapp.json,
 *   - someone without the app pastes `irm http://host:3000/join.ps1 | iex`,
 *   - `npm run worker -- --server host` reads the token out of /join.sh,
 *   - the coordinator's mDNS record already points peers at port 3000.
 *
 * Same trust model as GradMesh: on a LAN, being on the network is the boundary,
 * and the token is shown to anyone who can reach this port. Only an explicit
 * allowlist of agent files is served; nothing else on disk is reachable.
 */

const http = require("node:http");
const fs = require("node:fs");
const path = require("node:path");

const { AGENT_FILES } = require("./agent");
const { engineDir, assetsDir } = require("./paths");

const AGENT_SET = new Set(AGENT_FILES);

function powershellScript({ web, coordinator, token }) {
  const files = AGENT_FILES.map((file) => `'${file}'`).join(", ");
  return `# GradMesh worker installer, served by GradApp
# Generated by ${web}. Joins this machine's GPU to that mesh.
# Everything is installed under $HOME\\.gradmesh\\agent; nothing system-wide.
# Prefer one click? Get the GradApp desktop app and press Join.

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$MeshWeb = '${web}'
$MeshCoordinator = '${coordinator}'
$MeshToken = '${token}'
$AgentRoot = Join-Path $HOME '.gradmesh\\agent'

Write-Host ""
Write-Host "GradMesh worker" -ForegroundColor Green
Write-Host "  joining $MeshCoordinator" -ForegroundColor DarkGray
Write-Host ""

function Find-Python {
  foreach ($candidate in @('py -3.12', 'py -3.11', 'py -3.13', 'py -3.10', 'python', 'python3')) {
    $parts = @($candidate.Split(' '))
    $exe = $parts[0]
    $rest = @()
    if ($parts.Count -gt 1) { $rest = @($parts[1..($parts.Count - 1)]) }
    try {
      $version = & $exe @rest -c "import sys; print(sys.version_info.major * 100 + sys.version_info.minor)" 2>$null
      if ($LASTEXITCODE -eq 0 -and [int]$version -ge 310 -and [int]$version -le 313) {
        return ,(@($exe) + $rest)
      }
    } catch { }
  }
  return $null
}

$Python = Find-Python
if (-not $Python) {
  Write-Host "  Python 3.10 to 3.13 is needed and was not found." -ForegroundColor Yellow
  $winget = Get-Command winget -ErrorAction SilentlyContinue
  $answer = 'n'
  if ($winget) {
    try { $answer = Read-Host "  Install Python 3.12 for your user account now with winget? [Y/n]" } catch { $answer = 'n' }
  }
  if ($winget -and ($answer -eq '' -or $answer -match '^[Yy]')) {
    winget install --id Python.Python.3.12 -e --scope user --silent --accept-package-agreements --accept-source-agreements | Out-Host
    $env:Path = [Environment]::GetEnvironmentVariable('Path', 'User') + ';' + [Environment]::GetEnvironmentVariable('Path', 'Machine')
    $Python = Find-Python
  }
  if (-not $Python) {
    Write-Host "  Install Python 3.12, then open a new PowerShell and run this command again:" -ForegroundColor Red
    Write-Host "    winget install Python.Python.3.12" -ForegroundColor Yellow
    return
  }
}
$PythonExe = $Python[0]
$PythonArgs = @()
if ($Python.Count -gt 1) { $PythonArgs = @($Python[1..($Python.Count - 1)]) }
Write-Host "  found Python: $($Python -join ' ')" -ForegroundColor Green

New-Item -ItemType Directory -Force -Path $AgentRoot | Out-Null
Write-Host "  downloading the agent" -ForegroundColor DarkGray
foreach ($file in @(${files})) {
  $target = Join-Path $AgentRoot $file
  $attempt = 0
  while ($true) {
    try {
      Invoke-WebRequest -Uri "$MeshWeb/api/agent/$file" -OutFile $target -UseBasicParsing -TimeoutSec 60
      break
    } catch {
      $attempt += 1
      if ($attempt -ge 3) {
        Write-Host "  Could not download $file from $MeshWeb. Is this machine on the same network as the host?" -ForegroundColor Red
        return
      }
      Start-Sleep -Seconds 2
    }
  }
}

& $PythonExe @PythonArgs (Join-Path $AgentRoot 'setup_env.py') agent --server $MeshCoordinator --token $MeshToken --name $env:COMPUTERNAME
`;
}

function shellScript({ web, coordinator, token }) {
  const files = AGENT_FILES.join(" ");
  return `#!/bin/sh
# GradMesh worker installer, served by GradApp
# Generated by ${web}. Joins this machine's GPU to that mesh.
# Everything is installed under ~/.gradmesh/agent; nothing system-wide.
# Prefer one click? Get the GradApp desktop app and press Join.
set -e

MESH_WEB="${web}"
MESH_COORDINATOR="${coordinator}"
MESH_TOKEN="${token}"
AGENT_ROOT="$HOME/.gradmesh/agent"

printf '\\n\\033[32mGradMesh worker\\033[0m\\n'
printf '\\033[90m  joining %s\\033[0m\\n\\n' "$MESH_COORDINATOR"

RUN=""
CANDIDATES="python3.12 python3.11 python3.13 python3.10 python3 python"
if [ "$(uname -s)" = "Darwin" ]; then
  if [ "$(sysctl -n hw.optional.arm64 2>/dev/null)" = "1" ]; then
    RUN="/usr/bin/arch -arm64"
  fi
  CANDIDATES="/opt/homebrew/bin/python3.12 /opt/homebrew/bin/python3.11 /opt/homebrew/bin/python3.13 /opt/homebrew/bin/python3.10
              /Library/Frameworks/Python.framework/Versions/3.12/bin/python3
              /Library/Frameworks/Python.framework/Versions/3.11/bin/python3
              /Library/Frameworks/Python.framework/Versions/3.13/bin/python3
              python3.12 python3.11 python3.13 python3.10
              /usr/local/bin/python3.12 /usr/local/bin/python3.11 /usr/local/bin/python3.13 python3"
fi
PYTHON=""
for candidate in $CANDIDATES; do
  resolved=$(command -v "$candidate" 2>/dev/null) || continue
  [ "$resolved" = "/usr/bin/python3" ] && [ "$(uname -s)" = "Darwin" ] && continue
  version=$($RUN "$resolved" -c 'import sys; print(sys.version_info.major * 100 + sys.version_info.minor)' 2>/dev/null || echo 0)
  if [ "$version" -ge 310 ] 2>/dev/null && [ "$version" -le 313 ] 2>/dev/null; then
    PYTHON="$resolved"
    break
  fi
done

if [ -z "$PYTHON" ]; then
  printf '\\033[31m  Python 3.10 to 3.13 is needed and was not found.\\033[0m\\n'
  case "$(uname -s)" in
    Darwin) printf '\\033[33m    brew install python@3.12\\033[0m\\n' ;;
    *)      printf '\\033[33m    Ubuntu/Debian:  sudo apt install python3.12 python3.12-venv\\033[0m\\n'
            printf '\\033[33m    Fedora:         sudo dnf install python3.12\\033[0m\\n' ;;
  esac
  printf '\\033[90m  Then run this command again.\\033[0m\\n'
  exit 1
fi
printf '\\033[32m  found Python: %s\\033[0m\\n' "$PYTHON"

mkdir -p "$AGENT_ROOT"
printf '\\033[90m  downloading the agent\\033[0m\\n'
fetch() {
  if command -v curl >/dev/null 2>&1; then
    curl -fsSL --retry 3 --retry-delay 2 "$1" -o "$2"
  else
    wget -q --tries=3 "$1" -O "$2"
  fi
}
for file in ${files}; do
  if ! fetch "$MESH_WEB/api/agent/$file" "$AGENT_ROOT/$file"; then
    printf '\\033[31m  Could not download %s. Is this machine on the same network as the host?\\033[0m\\n' "$file"
    exit 1
  fi
done

exec $RUN "$PYTHON" "$AGENT_ROOT/setup_env.py" agent \\
  --server "$MESH_COORDINATOR" \\
  --token "$MESH_TOKEN" \\
  --name "$(hostname)"
`;
}

